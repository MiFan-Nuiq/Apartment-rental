#!/usr/bin/env bash
# ============================================================================
# clean.sh —— 清理自动化测试运行产物
#
# 用途：
#   一键删除 pytest / Allure / Playwright 在运行过程中生成的临时目录与缓存文件，
#   让下一次执行从"干净状态"开始，避免旧的失败截图、旧的 trace、
#   旧的环境变量覆盖记录、旧的 Allure 结果混进新一次的报告里。
#
# 用法：
#   ./clean.sh                  # 在脚本所在目录（test/automation）执行清理
#   bash clean.sh               # 不想加可执行权限时的等价写法
#
# 清理范围：
#   allure-results/   Allure 原始 JSON 数据
#   allure-report/    Allure 静态 HTML 报告
#   screenshots/      UI 用例失败截图
#   traces/           Playwright trace 压缩包
#   .pytest_cache/    pytest 缓存（含 lastfailed，会影响 --lf 的判定）
#   所有 __pycache__/ 与 *.pyc（Python 字节码缓存，递归清理）
#
# 注意事项：
#   1) 本脚本只删除"运行产物"，不会动任何源码、用例、配置或 SQL 文件；
#   2) 删除不可恢复——allure-report 是纯生成物，删掉后重新跑测试即可再生；
#   3) 脚本会自动切换到自身所在目录执行，因此可以在任意路径下调用它；
#   4) 目录不存在时只提示"无需清理"，不会报错退出（set -e 下也能安全重复执行）。
#
# 退出码：
#   0  清理完成（含"本来就没有产物"的情况）
# ============================================================================

# -e：任一命令失败立即退出，避免出错后继续删错东西
# -u：使用未定义变量时报错，防止变量名拼错导致误删
# -o pipefail：管道中任一环节失败即视为失败
set -euo pipefail

# 切换到脚本所在目录：保证无论从哪个路径调用，清理的都是 test/automation 下的产物
cd "$(dirname "$0")"

echo "=========================================="
echo "开始清理自动化测试产物"
echo "工作目录：$(pwd)"
echo "=========================================="

# ---------------------------------------------------------------------------
# 一、清理固定的产物目录
# ---------------------------------------------------------------------------
# 用数组统一管理，便于后续增删；逐个判断是否存在，存在才删并打印提示
DIRS=(
  "allure-results"   # Allure 原始数据
  "allure-report"    # Allure 静态报告
  "screenshots"      # UI 失败截图
  "traces"           # Playwright trace
  ".pytest_cache"    # pytest 缓存
)

for dir in "${DIRS[@]}"; do
  if [ -d "$dir" ]; then
    # -rf 递归强制删除，不加 -v 以免刷屏；删除结果由下面的中文提示呈现
    rm -rf "$dir"
    echo "已清理 ${dir}"
  else
    # 目录不存在属于正常情况（例如从没跑过 UI 用例），提示后继续
    echo "跳过 ${dir}（目录不存在，无需清理）"
  fi
done

# ---------------------------------------------------------------------------
# 二、递归清理 __pycache__ 目录
# ---------------------------------------------------------------------------
# -type d 只找目录；-prune 阻止 find 进入已匹配目录内部，避免"边删边遍历"的报错；
# -exec ... + 批量传给 rm，比逐个调用效率高
PYCACHE_COUNT=$(find . -type d -name "__pycache__" -prune | wc -l | tr -d ' ')
if [ "$PYCACHE_COUNT" -gt 0 ]; then
  find . -type d -name "__pycache__" -prune -exec rm -rf {} +
  echo "已清理 __pycache__ 目录（共 ${PYCACHE_COUNT} 个）"
else
  echo "跳过 __pycache__（未找到，无需清理）"
fi

# ---------------------------------------------------------------------------
# 三、递归清理 *.pyc 字节码文件
# ---------------------------------------------------------------------------
# 正常情况下 __pycache__ 删除后 .pyc 也随之消失，
# 这里再兜底扫一遍散落在其他位置的 .pyc，保证清理彻底
PYC_COUNT=$(find . -type f -name "*.pyc" | wc -l | tr -d ' ')
if [ "$PYC_COUNT" -gt 0 ]; then
  find . -type f -name "*.pyc" -delete
  echo "已清理 *.pyc 文件（共 ${PYC_COUNT} 个）"
else
  echo "跳过 *.pyc（未找到，无需清理）"
fi

# 完成提示：成功走到这里说明上面的命令都没有报错
echo "=========================================="
echo "清理完成"
echo "=========================================="